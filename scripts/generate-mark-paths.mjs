/**
 * One-shot outline builder for the approved fluid AWX mark.
 * Geometry matches reference/awxforge-mark-fluid.html. Do not tweak the curves here.
 */
import { mkdirSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function point(p, t) {
  const u = 1 - t;
  return [
    u * u * u * p[0][0] + 3 * u * u * t * p[1][0] + 3 * u * t * t * p[2][0] + t * t * t * p[3][0],
    u * u * u * p[0][1] + 3 * u * u * t * p[1][1] + 3 * u * t * t * p[2][1] + t * t * t * p[3][1],
  ];
}

function derivative(p, t) {
  const u = 1 - t;
  return [
    3 *
      (u * u * (p[1][0] - p[0][0]) + 2 * u * t * (p[2][0] - p[1][0]) + t * t * (p[3][0] - p[2][0])),
    3 *
      (u * u * (p[1][1] - p[0][1]) + 2 * u * t * (p[2][1] - p[1][1]) + t * t * (p[3][1] - p[2][1])),
  ];
}

function build(segments, widthAt) {
  const left = [];
  const right = [];
  const samples = 36;

  segments.forEach((segment, index) => {
    for (let step = 0; step <= samples; step += 1) {
      if (step === samples && index < segments.length - 1) break;
      const t = step / samples;
      const p = point(segment, t);
      const d = derivative(segment, t);
      const length = Math.hypot(d[0], d[1]) || 1;
      const half = widthAt(index, t) / 2;
      const nx = -d[1] / length;
      const ny = d[0] / length;
      left.push(`${(p[0] + nx * half).toFixed(2)} ${(p[1] + ny * half).toFixed(2)}`);
      right.push(`${(p[0] - nx * half).toFixed(2)} ${(p[1] - ny * half).toFixed(2)}`);
    }
  });

  const outline = `M${left.join("L")}L${right.reverse().join("L")}Z`;
  const center = `M${segments[0][0].join(" ")}${segments
    .map((segment) => `C${segment[1].join(" ")} ${segment[2].join(" ")} ${segment[3].join(" ")}`)
    .join("")}`;

  return { outline, center };
}

