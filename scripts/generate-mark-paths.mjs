const NODE_WIDTHS = [1.6, 7.5, 7.5, 7.5, 7.5, 6.5, 1.1];

function mainWidth(index, t) {
  const blend = index === 0 || index === 5 ? t * t * (3 - 2 * t) : t;
  const base = NODE_WIDTHS[index] + (NODE_WIDTHS[index + 1] - NODE_WIDTHS[index]) * blend;
  const sine = Math.sin(Math.PI * t);
  const pressure = index % 2 === 1 ? 1 + 0.32 * sine : index < 5 ? 1 - 0.3 * sine : 1;
  return base * pressure;
}

const CROSS = [
  [
    [170, 8],
    [194, 26],
    [208, 62],
    [236, 94],
  ],
];

function crossWidth(_index, t) {
  return 1.4 + 8.8 * Math.sin(Math.PI * t ** 0.85) ** 0.7;
}

const X_INK = [
  [
    [174, 92],
    [190, 74],
    [204, 30],
    [232, 6],
  ],
];

const X_ORANGE = [
  [
    [174, 6],
    [196, 30],
    [210, 62],
    [232, 92],
  ],
];

function xWidth(_index, t) {
  return 2 + 9.5 * Math.sin(Math.PI * t) ** 0.6;
}

const fullInk = build(MAIN, mainWidth);
const fullOrange = build(CROSS, crossWidth);
const compactInk = build(X_INK, xWidth);
const compactOrange = build(X_ORANGE, xWidth);

